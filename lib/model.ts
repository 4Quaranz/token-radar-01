// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds
// pre-token protocols below the watchlist floor: the early rows the radar exists to find. A protocol
// is pre-token when its index entry records no token (no market cap, no CoinGecko id, no symbol);
// the snapshot's live-token protocols are kept apart and shown as the market's own values, never
// mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures. The one number no other radar states
// by hand is the category multiple, and this model does not state it either: it reads it off the
// snapshot's own live-token protocols, per category, as the median of market-cap over TVL. A
// category whose live protocols trade at 0.34x their TVL prices a pre-token peer at 0.34x its TVL.
// Small samples are shrunk toward the snapshot's global median so one outlier cannot set a
// category's price, and the result is clamped to a sane band. No protocol name is ever
// special-cased: the same function scores every row, so a future snapshot with protocols that do
// not exist yet is scored the same way.
//
//   catMult    = shrink(median(mcap/tvl of live protocols in the category), global median)
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x GROWTH_WEIGHT
//   maturity   = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   breadth    = 1 + 0.02 x min(max(chains - 1, 0), 5)
//   implied    = max(1, round(tvl_usd x catMult x growthMult x maturity x breadth))
// A category with fewer than three live protocols cannot price itself and takes the global
// median, so one outlier never sets a category's price.
//
// The constants are the model's, stated in the dashboard and changeable in the model sandbox. The
// category multiples are the snapshot's, recomputed on every run and listed in the dashboard.

